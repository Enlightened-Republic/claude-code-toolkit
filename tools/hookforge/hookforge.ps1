#requires -Version 5.1
<#
.SYNOPSIS
    HookForge - YAML-to-hook handler generator for Claude Code.

.DESCRIPTION
    Subcommands:
        list                       - list built-in templates
        lint -Spec <file>          - lint a YAML spec
        generate -Spec <file> -OutDir <dir> - lint + generate handler + print settings fragment
        wire -Handler <path> -Event <name> -Matcher <regex> - emit a settings.json fragment for an existing handler

.PARAMETER Subcommand
    One of: list, lint, generate, wire

.PARAMETER Spec
    Path to YAML spec file.

.PARAMETER OutDir
    Output directory for generated handler.

.PARAMETER Handler
    Path to existing handler script (for `wire`).

.PARAMETER Event
    Claude Code hook event name (for `wire`).

.PARAMETER Matcher
    Tool matcher regex (for `wire`).
#>
