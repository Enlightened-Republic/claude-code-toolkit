# ---- YAML parser (subset sufficient for HookForge spec shape) ----
function Read-YamlSpec {
    param([string]$Path)
    if (-not (Test-Path $Path)) {
        throw "Spec file not found: $Path"
    }
    $lines = Get-Content $Path -Encoding UTF8
    $result = @{}
    $stack = New-Object System.Collections.Stack
    $stack.Push(@{ obj = $result; indent = -1 })
    foreach ($raw in $lines) {
        # Strip comments
        $line = $raw -replace '#.*$', ''
        if (-not $line.Trim()) { continue }
        $indent = ($line.Length - $line.TrimStart().Length)
        $trimmed = $line.Trim()

        # Pop stack to current indent
        while ($stack.Count -gt 1 -and $stack.Peek().indent -ge $indent) {
            $stack.Pop() | Out-Null
        }
        $current = $stack.Peek().obj

        if ($trimmed -match '^([\w_-]+):\s*(.*)$') {
            $key = $matches[1]
            $val = $matches[2].Trim()
            if (-not $val) {
                $newObj = @{}
                $current[$key] = $newObj
                $stack.Push(@{ obj = $newObj; indent = $indent })
            } elseif ($val.StartsWith('[') -and $val.EndsWith(']')) {
                $inner = $val.Substring(1, $val.Length - 2)
                $items = $inner.Split(',') | ForEach-Object { $_.Trim().Trim("'").Trim('"') }
                $current[$key] = $items
            } else {
                # Strip surrounding quotes
                $val = $val -replace '^["'']|["'']$', ''
                $current[$key] = $val
            }
        }
    }
    return $result
}

# ---- Linter ----
function Test-Spec {
    param($Spec)
    $errors = @()
    if (-not $Spec.name) { $errors += "Missing 'name'" }
    if (-not $Spec.event) { $errors += "Missing 'event'" }
    elseif ($Spec.event -notin $KNOWN_EVENTS) { $errors += "Unknown event '$($Spec.event)'. Valid: $($KNOWN_EVENTS -join ', ')" }
    if (-not $Spec.action) { $errors += "Missing 'action'" }
    elseif ($Spec.action -notin @('block','warn','allow','log','transform')) {
        $errors += "Invalid action '$($Spec.action)'. Valid: block, warn, allow, log, transform"
    }
    if (($Spec.action -in @('block','warn')) -and -not $Spec.reason) {
        $errors += "action=$($Spec.action) requires 'reason'"
    }
    if ($Spec.matcher) {
        try { [void][regex]::new($Spec.matcher) } catch { $errors += "Invalid matcher regex: $_" }
    }
    if ($Spec.when -and $Spec.when.file_path_matches) {
        try { [void][regex]::new($Spec.when.file_path_matches) } catch { $errors += "Invalid when.file_path_matches: $_" }
    }
    if ($Spec.when -and $Spec.when.command_matches) {
        try { [void][regex]::new($Spec.when.command_matches) } catch { $errors += "Invalid when.command_matches: $_" }
    }
    return $errors
}

# ---- Codegen ----
function Get-Template {
    param([string]$Name)
    if ($INLINE_TEMPLATES.ContainsKey($Name)) { return $INLINE_TEMPLATES[$Name] }
    if ($TEMPLATE_DIR) {
        $path = Join-Path $TEMPLATE_DIR "$Name.ps1.tpl"
        if (Test-Path $path) { return (Get-Content $path -Raw) }
    }
    throw "Template not found: $Name"
}

function Resolve-Template {
    param([string]$TemplateName, $Spec)

    # Build CONDITION_BLOCK based on `when:`
    $conditionBlock = "`$shouldBlock = `$true"
    if ($Spec.when) {
        $checks = @()
        if ($Spec.when.file_path_matches) {
            $r = $Spec.when.file_path_matches -replace "'", "''"
            $checks += "([string]`$event.tool_input.file_path -match '$r')"
        }
        if ($Spec.when.command_matches) {
            $r = $Spec.when.command_matches -replace "'", "''"
            $checks += "([string]`$event.tool_input.command -match '$r')"
        }
        if ($Spec.when.tool_name_in) {
            $names = ($Spec.when.tool_name_in | ForEach-Object { "'$_'" }) -join ','
            $checks += "(`$event.tool_name -in @($names))"
        }
        if ($Spec.when.prompt_matches) {
            $r = $Spec.when.prompt_matches -replace "'", "''"
            $checks += "([string]`$event.user_prompt -match '$r')"
        }
        if ($checks.Count -gt 0) {
            $conditionBlock = "`$shouldBlock = $($checks -join ' -and ')"
        }
    }

    $tpl = Get-Template -Name $TemplateName
    $reason = if ($Spec.reason) { ($Spec.reason -replace '"', '`"') } else { "Blocked by HookForge" }

    # Resolve every placeholder value first (PS 5.1 has no inline `(if ...)` expression).
    $auditFile = if ($Spec.output -and $Spec.output.audit_file) { [string]$Spec.output.audit_file } else { '~/.claude/hookforge-audit.log' }
    $commandRegex = if ($Spec.when -and $Spec.when.command_matches) { [string]$Spec.when.command_matches } else { '.*' }
    $replaceRegex = if ($Spec.transform -and $Spec.transform.replace_regex) { [string]$Spec.transform.replace_regex } else { '' }
    $withValue = if ($Spec.transform -and $Spec.transform.with) { [string]$Spec.transform.with } else { '' }
    $injectedContext = if ($Spec.inject_context) { [string]$Spec.inject_context } else { 'Context injected by HookForge' }

    $allowedPaths = ''
    if ($Spec.when -and $Spec.when.allowed_paths) {
        $allowedPaths = (@($Spec.when.allowed_paths) | ForEach-Object { "'" + ($_ -replace "'", "''") + "'" }) -join ','
    }
    $allowedDomains = ''
    if ($Spec.when -and $Spec.when.allowed_domains) {
        $allowedDomains = (@($Spec.when.allowed_domains) | ForEach-Object { "'" + ($_ -replace "'", "''") + "'" }) -join ','
    }

    # Literal .Replace() (not -replace) so values containing regex/replacement
    # metacharacters ($, \, {{ }}) pass through verbatim.
    $resolved = $tpl
    $resolved = $resolved.Replace('{{SPEC_NAME}}', [string]$Spec.name)
    $resolved = $resolved.Replace('{{EVENT}}', [string]$Spec.event)
    $resolved = $resolved.Replace('{{REASON}}', [string]$reason)
    $resolved = $resolved.Replace('{{CONDITION_BLOCK}}', [string]$conditionBlock)
    $resolved = $resolved.Replace('{{AUDIT_FILE}}', $auditFile)
    $resolved = $resolved.Replace('{{COMMAND_REGEX}}', $commandRegex)
    $resolved = $resolved.Replace('{{ALLOWED_PATHS}}', $allowedPaths)
    $resolved = $resolved.Replace('{{ALLOWED_DOMAINS}}', $allowedDomains)
    $resolved = $resolved.Replace('{{REPLACE_REGEX}}', $replaceRegex)
    $resolved = $resolved.Replace('{{WITH}}', $withValue)
    $resolved = $resolved.Replace('{{INJECTED_CONTEXT}}', $injectedContext)

    return $resolved
}

# ---- Subcommands ----
switch ($Subcommand.ToLower()) {
    'help' {
        Write-Output "HookForge - YAML-to-hook generator for Claude Code"
        Write-Output ""
        Write-Output "Subcommands:"
        Write-Output "  list                                   List built-in templates"
        Write-Output "  lint -Spec <file>                      Lint a YAML spec"
        Write-Output "  generate -Spec <file> -OutDir <dir>    Generate handler + settings fragment"
        Write-Output "  wire -Handler <path> -Event <name> -Matcher <regex>   Emit settings fragment"
        Write-Output ""
        Write-Output "Hook events: $($KNOWN_EVENTS -join ', ')"
        exit 0
    }

    'list' {
        Write-Output "Built-in templates:"
        foreach ($k in ($INLINE_TEMPLATES.Keys | Sort-Object)) {
            Write-Output "  - $k"
        }
        exit 0
    }

    'lint' {
        if (-not $Spec) { Write-Error "lint requires -Spec"; exit 2 }
        $parsed = Read-YamlSpec -Path $Spec
        $errors = Test-Spec -Spec $parsed
        if ($errors.Count -gt 0) {
            Write-Output "LINT FAILED:"
            foreach ($e in $errors) { Write-Output "  - $e" }
            exit 2
        }
        Write-Output "LINT OK: $($parsed.name) ($($parsed.event) -> $($parsed.action))"
        exit 0
    }

    'generate' {
        if (-not $Spec) { Write-Error "generate requires -Spec"; exit 2 }
        $parsed = Read-YamlSpec -Path $Spec
        $errors = Test-Spec -Spec $parsed
        if ($errors.Count -gt 0) {
            Write-Output "LINT FAILED:"
            foreach ($e in $errors) { Write-Output "  - $e" }
            exit 2
        }

        # Pick template
        $templateName = switch ($parsed.event) {
            'PreToolUse'        { if ($parsed.when.command_matches) { 'block-bash-pattern' } elseif ($parsed.when.allowed_domains) { 'web-fetch-allowlist' } elseif ($parsed.when.allowed_paths -or ($parsed.when.tool_name_in -and ('Write' -in $parsed.when.tool_name_in -or 'Edit' -in $parsed.when.tool_name_in))) { 'enforce-write-permissions' } else { 'block-on-condition' } }
            'PostToolUse'       { 'audit-tool-call' }
            'SessionStart'      { 'session-start-banner' }
            'UserPromptSubmit'  { if ($parsed.action -eq 'transform') { 'transform-prompt' } else { 'hook-with-context-injection' } }
            'Stop'              { 'stop-on-condition' }
            'SubagentStart'     { 'log-subagent-spawn' }
            default             { 'block-on-condition' }
        }

        if (-not (Test-Path $OutDir)) { New-Item -ItemType Directory -Path $OutDir -Force | Out-Null }
        $outPath = Join-Path $OutDir "$($parsed.name).ps1"
        $content = Resolve-Template -TemplateName $templateName -Spec $parsed
        Set-Content -Path $outPath -Value $content -Encoding UTF8

        $fragment = @{
            hooks = @{
                $parsed.event = @(
                    @{
                        matcher = if ($parsed.matcher) { $parsed.matcher } else { '' }
                        hooks = @(
                            @{
                                type = 'command'
                                command = "pwsh -NoProfile -File $outPath"
                            }
                        )
                    }
                )
            }
        } | ConvertTo-Json -Depth 6

        Write-Output "Generated: $outPath"
        Write-Output ""
        Write-Output "Paste this into ~/.claude/settings.json (merge with existing hooks):"
        Write-Output "---"
        Write-Output $fragment
        exit 0
    }

    'wire' {
        if (-not $Handler -or -not $Event) { Write-Error "wire requires -Handler and -Event"; exit 2 }
        $fragment = @{
            hooks = @{
                $Event = @(
                    @{
                        matcher = $Matcher
                        hooks = @(
                            @{
                                type = 'command'
                                command = "pwsh -NoProfile -File $Handler"
                            }
                        )
                    }
                )
            }
        } | ConvertTo-Json -Depth 6
        Write-Output $fragment
        exit 0
    }

    default {
        Write-Error "Unknown subcommand: $Subcommand. Use 'help'."
        exit 2
    }
}
